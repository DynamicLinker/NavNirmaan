"""
build_walkable_scene.py
=======================
Blender Python pipeline script for converting a 2D-floor-plan-derived
3MF house mesh (generated by OpenSCAD) into a fully configured, walkable
Blender scene.

Usage (from the command line):
    blender -b -P build_walkable_scene.py -- house_model.3mf interactive_house.blend

Arguments after '--' are parsed by this script:
    argv[0]  ->  Path to the input .3mf file
    argv[1]  ->  Path for the output .blend file

Pipeline Steps:
    1. Scene Initialization   - Clear default objects, parse CLI args.
    2. Mesh Import            - Parse the .3mf natively (stdlib), write a
                                temp OBJ, import via wm.obj_import, then
                                bake per-face colors into a vertex color
                                attribute.
    3. Vertex Color Material  - PBR Principled BSDF driven by vertex colors.
    4. Sky & Lighting         - Cycles engine + Nishita Sky for daylight.
    5. First-Person Camera    - "Player_Camera" at eye-level inside the mesh.
    6. Save & Exit            - Write the .blend file and quit cleanly.

Note on Blender 5.2 compatibility:
    Blender 5.2 no longer bundles the io_scene_3mf add-on, so
    bpy.ops.import_mesh.threemf does not exist.  A .3mf file is a ZIP
    archive containing XML geometry (3D Manufacturing Format spec).  We
    parse it with stdlib zipfile + xml.etree.ElementTree, convert to a
    temporary .obj + .mtl, import with bpy.ops.wm.obj_import, and then
    bake the per-face material colors into a Blender vertex color layer.
"""

import sys
import math
import os
import tempfile
import zipfile
import xml.etree.ElementTree as ET
import bpy


# =============================================================================
# STEP 0 - Utility helpers
# =============================================================================

def log(msg: str) -> None:
    """Simple timestamped logger so progress is visible in the Blender console."""
    print(f"[build_walkable_scene] {msg}", flush=True)


def deselect_all() -> None:
    """Deselect every object in the scene."""
    bpy.ops.object.select_all(action='DESELECT')


def select_obj(obj: bpy.types.Object) -> None:
    """Select *obj* and make it the active object."""
    deselect_all()
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj


