def save_blend(output_path: str) -> None:
    """
    Persist the fully configured scene to disk as a .blend file.

    Uses compress=True to apply zlib compression, which meaningfully reduces
    file size for scenes with large vertex-color meshes.

    Args:
        output_path: Destination file path for the .blend file.
    """
    log(f"Saving .blend file to: {output_path} ...")

    bpy.ops.wm.save_as_mainfile(filepath=output_path, compress=True)

    log("Scene saved successfully. Pipeline complete.")


