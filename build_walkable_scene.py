def parse_cli_args() -> tuple:
    """
    Parse the input .3mf and output .blend paths from the command line.

    Supports two invocation modes:

    1. Via Blender (canonical):
            blender -b -P build_walkable_scene.py -- house.3mf out.blend
       Blender inserts a '--' separator; we slice everything after it.

    2. Direct Python (development / bpy-pip):
            python build_walkable_scene.py house.3mf out.blend
       No '--' separator; we treat sys.argv[1] and sys.argv[2] directly.

    Returns:
        (input_3mf_path, output_blend_path) as a tuple of strings.
    """
    # --- Mode 1: Blender wrapper (has '--' separator) -----------------------
    if "--" in sys.argv:
        separator_index = sys.argv.index("--")
        script_args = sys.argv[separator_index + 1:]
        mode = "blender-wrapped"

    # --- Mode 2: Direct Python invocation (no '--') -------------------------
    else:
        # sys.argv[0] is the script name; [1] and [2] are the user args.
        script_args = sys.argv[1:]
        mode = "direct-python"

    if len(script_args) < 2:
        raise SystemExit(
            "ERROR: Expected 2 path arguments.\n\n"
            "  Via Blender :\n"
            "    blender -b -P build_walkable_scene.py -- "
            "house_model.3mf interactive_house.blend\n\n"
            "  Direct Python:\n"
            "    python build_walkable_scene.py "
            "house_model.3mf interactive_house.blend\n\n"
            f"Received ({mode}): {script_args}"
        )

    input_path  = script_args[0]
    output_path = script_args[1]
    log(f"Invocation mode : {mode}")
    log(f"Input  .3mf     : {input_path}")
    log(f"Output .blend   : {output_path}")
    return input_path, output_path


def clear_default_scene() -> None:
    """
    Remove every object that Blender places in a new scene by default
    (Cube, Camera, Light) so we start with a completely empty slate.
    Also purge orphaned data-blocks to keep the file clean.
    """
    log("Clearing default scene objects ...")

    # Iterate over a *copy* because we modify bpy.data.objects in-place.
    for obj in list(bpy.data.objects):
        bpy.data.objects.remove(obj, do_unlink=True)

    # Purge orphaned mesh, light, and camera data-blocks.
    for mesh in list(bpy.data.meshes):
        bpy.data.meshes.remove(mesh)
    for light in list(bpy.data.lights):
        bpy.data.lights.remove(light)
    for camera in list(bpy.data.cameras):
        bpy.data.cameras.remove(camera)

    log("Default scene cleared.")


