# The 3MF spec defines geometry inside a ZIP archive.  The main model file
# is typically "3D/3dmodel.model" and uses the namespace:
_3MF_NS = "http://schemas.microsoft.com/3dmanufacturing/core/2015/02"


def _parse_3mf_to_obj(filepath: str, obj_path: str, mtl_path: str) -> None:
    """
    Parse a .3mf file and write an equivalent Wavefront OBJ + MTL pair.

    3MF geometry lives in a ZIP archive under "3D/3dmodel.model".
    Each <object> element contains:
        <vertices>  ->  <vertex x y z>  entries.
        <triangles> ->  <triangle v1 v2 v3 pid p1> entries.
    The optional 'pid' / 'p1' attributes reference a <basematerials>
    palette which stores the RGB colors assigned via OpenSCAD color().

    We convert each material in the palette to a named MTL entry, then
    write per-face 'usemtl' directives so that after import Blender gives
    each face the correct color.  We then bake those per-face material
    colors into a vertex color attribute.

    Args:
        filepath : Path to the source .3mf file.
        obj_path : Destination path for the .obj text file.
        mtl_path : Destination path for the .mtl text file.
    """
    log(f"Parsing .3mf with stdlib XML parser: {filepath}")

    mtl_filename = os.path.basename(mtl_path)

    with zipfile.ZipFile(filepath, 'r') as zf:
        # Locate the primary model file (spec default: "3D/3dmodel.model").
        model_entry = None
        for name in zf.namelist():
            if name.lower().endswith(".model"):
                model_entry = name
                break
        if model_entry is None:
            raise RuntimeError(
                f"No .model entry found inside '{filepath}'. "
                "Is this a valid .3mf file?"
            )
        log(f"Found model entry: {model_entry}")
        model_xml = zf.read(model_entry)

    root = ET.fromstring(model_xml)
    ns   = {'m': _3MF_NS}

    # --- Parse material palettes (basematerials) ----------------------------
    # Maps palette_id -> {material_index -> (r, g, b)}  (floats 0-1)
    palettes: dict[str, dict[int, tuple]] = {}
    for bm in root.findall('.//m:basematerials', ns):
        pid = bm.get('id', '0')
        colors: dict[int, tuple] = {}
        for idx, base in enumerate(bm.findall('m:base', ns)):
            raw = base.get('displaycolor', '#FFFFFF')
            # displaycolor is a CSS hex string: #RRGGBB or #RRGGBBAA
            raw = raw.lstrip('#')
            r = int(raw[0:2], 16) / 255.0
            g = int(raw[2:4], 16) / 255.0
            b = int(raw[4:6], 16) / 255.0
            colors[idx] = (r, g, b)
        palettes[pid] = colors
        log(f"Palette '{pid}': {len(colors)} color(s).")

    # --- Build MTL file from palette colors ----------------------------------
    # mat name: "mat_{pid}_{index}"  e.g. "mat_1_0"
    mat_entries: dict[str, tuple] = {}  # name -> (r, g, b)
    for pid, colors in palettes.items():
        for idx, rgb in colors.items():
            mat_name = f"mat_{pid}_{idx}"
            mat_entries[mat_name] = rgb

    # Fallback white material used when no palette reference is present.
    mat_entries['mat_default'] = (0.8, 0.8, 0.8)

    with open(mtl_path, 'w') as mf:
        mf.write(f"# Generated by build_walkable_scene.py\n")
        for mname, (r, g, b) in mat_entries.items():
            mf.write(f"\nnewmtl {mname}\n")
            mf.write(f"Ka {r:.6f} {g:.6f} {b:.6f}\n")   # ambient
            mf.write(f"Kd {r:.6f} {g:.6f} {b:.6f}\n")   # diffuse
            mf.write(f"Ks 0.1 0.1 0.1\n")                # specular
            mf.write(f"Ns 10.0\n")                        # shininess
            mf.write(f"d 1.0\n")                          # opacity

    log(f"MTL written: {mtl_path} ({len(mat_entries)} materials)")

    # --- Parse geometry and write OBJ ----------------------------------------
    with open(obj_path, 'w') as of:
        of.write(f"# Generated by build_walkable_scene.py\n")
        of.write(f"mtllib {mtl_filename}\n\n")

        global_vertex_offset = 0  # OBJ vertex indices are 1-based and global.

        for obj_el in root.findall('.//m:object', ns):
            obj_id   = obj_el.get('id', 'unknown')
            obj_name = obj_el.get('name', f'object_{obj_id}').replace(' ', '_')
            mesh_el  = obj_el.find('m:mesh', ns)
            if mesh_el is None:
                continue

            of.write(f"o {obj_name}\n")

            # --- Vertices ---
            verts_el = mesh_el.find('m:vertices', ns)
            vertices = []
            if verts_el is not None:
                for v in verts_el.findall('m:vertex', ns):
                    x, y, z = float(v.get('x', 0)), float(v.get('y', 0)), float(v.get('z', 0))
                    vertices.append((x, y, z))
                    of.write(f"v {x:.8f} {y:.8f} {z:.8f}\n")

            # --- Triangles --------------------------------------------------
            # Group consecutive triangles that share the same material together
            # so we minimise 'usemtl' line changes.
            tris_el = mesh_el.find('m:triangles', ns)
            if tris_el is None:
                global_vertex_offset += len(vertices)
                continue

            triangles = tris_el.findall('m:triangle', ns)

            # Determine per-triangle material name.
            current_mat  = None
            base_offset  = global_vertex_offset  # offset for this object's verts

            of.write(f"usemtl mat_default\n")  # prime with a default
            current_mat = 'mat_default'

            for tri in triangles:
                v1 = int(tri.get('v1')) + base_offset + 1  # OBJ is 1-indexed
                v2 = int(tri.get('v2')) + base_offset + 1
                v3 = int(tri.get('v3')) + base_offset + 1

                pid = tri.get('pid')
                p1  = tri.get('p1')
                if pid is not None and p1 is not None:
                    mat_name = f"mat_{pid}_{p1}"
                else:
                    mat_name = 'mat_default'

                if mat_name not in mat_entries:
                    mat_name = 'mat_default'

                if mat_name != current_mat:
                    of.write(f"usemtl {mat_name}\n")
                    current_mat = mat_name

                of.write(f"f {v1} {v2} {v3}\n")

            global_vertex_offset += len(vertices)
            of.write("\n")

    log(f"OBJ written: {obj_path} ({global_vertex_offset} vertices total)")


def _bake_material_colors_to_vertex_color(obj: bpy.types.Object) -> None:
    """
    After importing an OBJ, Blender assigns a separate material slot to
    each 'usemtl' group.  This function reads the Kd (diffuse) color from
    each material and bakes it into a per-loop vertex color attribute so
    the rest of the pipeline (which expects vertex colors) works correctly.

    Steps:
        1. Create a new Color Attribute layer named 'Col'.
        2. For each face, look up the material in its slot, read its
           Kd-equivalent node color (or diffuse_color), and write that
           color to all loops of the face.
    """
    log("Baking per-face material colors into vertex color attribute ...")

    mesh = obj.data

    # Create the color attribute (per-loop, BYTE_COLOR for efficiency).
    if 'Col' in mesh.color_attributes:
        mesh.color_attributes.remove(mesh.color_attributes['Col'])
    col_attr = mesh.color_attributes.new(
        name='Col', type='BYTE_COLOR', domain='CORNER'
    )
    mesh.color_attributes.active_color = col_attr

    # Build a lookup: material_index -> (r, g, b)
    mat_color_map: dict[int, tuple] = {}
    for mat_idx, mat in enumerate(obj.data.materials):
        if mat is None:
            mat_color_map[mat_idx] = (0.8, 0.8, 0.8)
            continue
        # Try to read Kd from the Principled BSDF Base Color if nodes are on.
        if mat.use_nodes:
            bsdf = mat.node_tree.nodes.get('Principled BSDF')
            if bsdf:
                bc = bsdf.inputs['Base Color'].default_value
                mat_color_map[mat_idx] = (bc[0], bc[1], bc[2])
                continue
        # Fallback: use mat.diffuse_color.
        dc = mat.diffuse_color
        mat_color_map[mat_idx] = (dc[0], dc[1], dc[2])

    # Paint every loop with the color of its face's material.
    color_data = col_attr.data
    for poly in mesh.polygons:
        rgb = mat_color_map.get(poly.material_index, (0.8, 0.8, 0.8))
        for loop_idx in poly.loop_indices:
            cd = color_data[loop_idx]
            cd.color = (rgb[0], rgb[1], rgb[2], 1.0)

    log(f"Vertex colors baked across {len(mesh.polygons)} faces.")


def import_3mf(filepath: str) -> bpy.types.Object:
    """
    Import a .3mf house mesh into Blender 5.2.

    Blender 5.2 removed the io_scene_3mf add-on, so we use a two-stage
    approach that relies only on operators that exist in 5.2:

        Stage A – stdlib parse:
            Read the .3mf (a ZIP of XML) with Python's zipfile and
            xml.etree.ElementTree modules.  Extract vertices, triangles,
            and basematerial color palettes.  Write a temporary .obj + .mtl
            pair that encodes the colors as named materials.

        Stage B – Blender OBJ import:
            Call bpy.ops.wm.obj_import on the temp .obj file.
            Join any multiple resulting objects into one 'House_Mesh'.
            Bake the per-face material colors into a 'Col' vertex color
            attribute so the rest of the pipeline can read them uniformly.

    Args:
        filepath: Absolute or relative path to the .3mf file.

    Returns:
        The imported (and merged) mesh object named 'House_Mesh'.
    """
    log(f"Importing .3mf: {filepath} ...")

    # Resolve to an absolute path so temp files land next to it cleanly.
    abs_path = os.path.abspath(filepath)

    # Create temp OBJ and MTL paths alongside the source file.
    tmp_dir  = tempfile.mkdtemp()
    obj_path = os.path.join(tmp_dir, "house_temp.obj")
    mtl_path = os.path.join(tmp_dir, "house_temp.mtl")

    # --- Stage A: parse 3MF -> OBJ/MTL -------------------------------------
    _parse_3mf_to_obj(abs_path, obj_path, mtl_path)

    # --- Stage B: import OBJ into Blender ----------------------------------
    pre_import_names = {obj.name for obj in bpy.data.objects}

    # bpy.ops.wm.obj_import exists in Blender 4.0+ (replaces import_scene.obj).
    bpy.ops.wm.obj_import(
        filepath=obj_path,
        forward_axis='Y',    # 3MF Y-forward convention
        up_axis='Z',
    )

    new_objects = [
        obj for obj in bpy.data.objects
        if obj.name not in pre_import_names and obj.type == 'MESH'
    ]

    if not new_objects:
        raise RuntimeError(
            "No mesh objects were created after importing the converted OBJ. "
            f"Check that '{obj_path}' contains valid geometry."
        )

    log(f"OBJ import created {len(new_objects)} mesh object(s).")

    # --- Merge all objects --------------------------------------------------
    deselect_all()
    for obj in new_objects:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = new_objects[-1]

    if len(new_objects) > 1:
        log("Joining imported meshes into a single object ...")
        bpy.ops.object.join()

    house_obj = bpy.context.view_layer.objects.active
    house_obj.name = "House_Mesh"

    # --- Bake material colors -> vertex color attribute ---------------------
    _bake_material_colors_to_vertex_color(house_obj)

    # --- Clean up temp files ------------------------------------------------
    try:
        os.remove(obj_path)
        os.remove(mtl_path)
        os.rmdir(tmp_dir)
        log("Temporary OBJ/MTL files removed.")
    except OSError as e:
        log(f"WARNING: Could not remove temp files: {e}")

    log(f"House mesh ready: '{house_obj.name}'")
    return house_obj


def apply_smooth_shading(obj: bpy.types.Object) -> None:
    """
    Apply Shade Smooth to the mesh and add an Edge Split modifier.

    Why Edge Split instead of the old Auto Smooth mesh property?
    - Blender 4.1+ removed 'mesh.use_auto_smooth' from the mesh data API.
    - Edge Split with a 30-degree threshold is the cross-version compatible
      approach: it keeps 90-degree architectural wall corners crisp while
      smoothing curved surfaces like arches or furniture.

    Threshold: 30 degrees
        - Edges whose dihedral angle exceeds 30 deg are split (rendered hard).
        - Right-angle walls (90 deg) are well above the threshold -> hard.
        - Gentle curves (< 30 deg between faces) -> smooth shading.
    """
    log("Applying shade-smooth + Edge Split modifier ...")

    select_obj(obj)

    # Mark all faces as smooth-shaded (no per-face hard/flat shading).
    bpy.ops.object.shade_smooth()

    # Add the Edge Split modifier.
    edge_split_mod = obj.modifiers.new(name="Edge_Split_Arch", type='EDGE_SPLIT')

    # 30 degrees in radians.
    edge_split_mod.split_angle   = math.radians(30)
    edge_split_mod.use_edge_angle = True   # Split by angle threshold.
    edge_split_mod.use_edge_sharp = False  # Ignore manually-marked sharp edges.

    log("Shade smooth + Edge Split (30 deg threshold) applied.")


