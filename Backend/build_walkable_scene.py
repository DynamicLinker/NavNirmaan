def setup_sky_and_lighting() -> None:
    """
    Switch the render engine to Cycles and add a Nishita Sky Texture as
    the World environment for physically-based outdoor daylight.

    Nishita Sky parameters used:
        sun_elevation  = 45 deg  -> mid-morning sun angle, good for shadows.
        sun_rotation   = 0 rad   -> sun located along the +Y axis.
        altitude       = 0 m     -> observer at sea level.
        air_density    = 1.0     -> standard clear atmosphere.
        dust_density   = 1.0     -> normal dust load.
        ozone_density  = 1.0     -> normal ozone layer.

    Cycles sample counts:
        128 samples (final) / 32 samples (preview) - good quality / speed
        balance for interactive use and quick test renders.
    """
    log("Setting up render engine and sky ...")

    scene = bpy.context.scene  # define scene first

    # Prefer EEVEE_NEXT (fast, real-time material colors); fall back to CYCLES.
    for engine in ('BLENDER_EEVEE_NEXT', 'BLENDER_EEVEE', 'CYCLES'):
        try:
            scene.render.engine = engine
            log(f"Render engine set to: {engine}")
            break
        except Exception:
            continue

    if scene.render.engine == 'CYCLES':
        scene.cycles.samples = 128
        scene.cycles.preview_samples = 32

    # Configure all open 3D Viewports to show Material Preview shading so
    # colors are visible the instant the .blend file is opened.
    for screen in bpy.data.screens:
        for area in screen.areas:
            if area.type == 'VIEW_3D':
                for space in area.spaces:
                    if space.type == 'VIEW_3D':
                        space.shading.type = 'MATERIAL'   # Material Preview mode
                        space.shading.use_scene_lights = True
                        space.shading.use_scene_world   = True
                        # In Solid mode, show material color instead of default grey
                        space.shading.color_type = 'MATERIAL'

    # --- World / sky node graph ---------------------------------------------
    world = bpy.data.worlds.new("Sky_World")
    scene.world = world
    world.use_nodes = True

    w_nodes = world.node_tree.nodes
    w_links = world.node_tree.links
    w_nodes.clear()

    # Background node controls overall sky brightness.
    bg_node = w_nodes.new(type='ShaderNodeBackground')
    bg_node.location = (300, 300)
    bg_node.inputs["Strength"].default_value = 1.0

    # Nishita physically-based sky texture.
    # NOTE: In Blender 5.x the sky_type enum was reorganised.
    # 'NISHITA' was split into 'SINGLE_SCATTERING' and 'MULTIPLE_SCATTERING'.
    # 'MULTIPLE_SCATTERING' is the high-quality equivalent of the old Nishita.
    sky_node = w_nodes.new(type='ShaderNodeTexSky')
    sky_node.location = (-100, 300)

    # Determine the correct sky type for this Blender version.
    sky_enum_values = sky_node.bl_rna.properties['sky_type'].enum_items.keys()
    if 'NISHITA' in sky_enum_values:
        # Blender 3.x / 4.x
        sky_node.sky_type = 'NISHITA'
        sky_node.sun_elevation  = math.radians(45)   # 45 degrees above horizon
        sky_node.sun_rotation   = 0.0                # Azimuth in radians
        sky_node.altitude       = 0.0
        sky_node.air_density    = 1.0
        sky_node.dust_density   = 1.0
        sky_node.ozone_density  = 1.0
        log("Sky type: NISHITA (Blender 3.x/4.x)")
    elif 'MULTIPLE_SCATTERING' in sky_enum_values:
        # Blender 5.x — NISHITA was renamed to MULTIPLE_SCATTERING
        sky_node.sky_type = 'MULTIPLE_SCATTERING'
        # sun_elevation and sun_rotation are still available in 5.x.
        if hasattr(sky_node, 'sun_elevation'):
            sky_node.sun_elevation = math.radians(45)
        if hasattr(sky_node, 'sun_rotation'):
            sky_node.sun_rotation  = 0.0
        log("Sky type: MULTIPLE_SCATTERING (Blender 5.x equivalent of Nishita)")
    else:
        # Last-resort fallback: pick whatever the first available type is.
        first_type = list(sky_enum_values)[0]
        sky_node.sky_type = first_type
        log(f"WARNING: Neither NISHITA nor MULTIPLE_SCATTERING found. "
            f"Using '{first_type}' as fallback sky type.")

    # World Output.
    world_output = w_nodes.new(type='ShaderNodeOutputWorld')
    world_output.location = (600, 300)

    # Link: Sky -> Background -> World Output.
    w_links.new(sky_node.outputs["Color"],       bg_node.inputs["Color"])
    w_links.new(bg_node.outputs["Background"],   world_output.inputs["Surface"])

    log("Cycles engine + Nishita Sky (45 deg sun elevation) configured.")


