# The 3MF spec defines geometry inside a ZIP archive.  The main model file
# is typically "3D/3dmodel.model" and uses the namespace:
_3MF_NS = "http://schemas.microsoft.com/3dmanufacturing/core/2015/02"


def _parse_3mf_to_obj(filepath: str, obj_path: str, mtl_path: str) -> None:
    """
    Parse a .3mf file and write an equivalent Wavefront OBJ + MTL pair.

    3MF geometry lives in a ZIP archive under "3D/3dmodel.model".
    Each <object> element contains:
        <vertices>  ->  <vertex x y z>  entries.
        <triangles> ->  <triangle v1 v2 v3 pid p1> entries.
    The optional 'pid' / 'p1' attributes reference a <basematerials>
    palette which stores the RGB colors assigned via OpenSCAD color().

    We convert each material in the palette to a named MTL entry, then
    write per-face 'usemtl' directives so that after import Blender gives
    each face the correct color.  We then bake those per-face material
    colors into a vertex color attribute.

    Args:
        filepath : Path to the source .3mf file.
        obj_path : Destination path for the .obj text file.
        mtl_path : Destination path for the .mtl text file.
    """
    log(f"Parsing .3mf with stdlib XML parser: {filepath}")

    mtl_filename = os.path.basename(mtl_path)

    with zipfile.ZipFile(filepath, 'r') as zf:
        # Locate the primary model file (spec default: "3D/3dmodel.model").
        model_entry = None
        for name in zf.namelist():
            if name.lower().endswith(".model"):
                model_entry = name
                break
        if model_entry is None:
            raise RuntimeError(
                f"No .model entry found inside '{filepath}'. "
                "Is this a valid .3mf file?"
            )
        log(f"Found model entry: {model_entry}")
        model_xml = zf.read(model_entry)

    root = ET.fromstring(model_xml)
    ns   = {'m': _3MF_NS}

    # --- Parse material palettes (basematerials) ----------------------------
    # Maps palette_id -> {material_index -> (r, g, b)}  (floats 0-1)
    palettes: dict[str, dict[int, tuple]] = {}
    for bm in root.findall('.//m:basematerials', ns):
        pid = bm.get('id', '0')
        colors: dict[int, tuple] = {}
        for idx, base in enumerate(bm.findall('m:base', ns)):
            raw = base.get('displaycolor', '#FFFFFF')
            # displaycolor is a CSS hex string: #RRGGBB or #RRGGBBAA
            raw = raw.lstrip('#')
            r = int(raw[0:2], 16) / 255.0
            g = int(raw[2:4], 16) / 255.0
            b = int(raw[4:6], 16) / 255.0
            colors[idx] = (r, g, b)
        palettes[pid] = colors
        log(f"Palette '{pid}': {len(colors)} color(s).")

    # --- Build MTL file from palette colors ----------------------------------
    # mat name: "mat_{pid}_{index}"  e.g. "mat_1_0"
    mat_entries: dict[str, tuple] = {}  # name -> (r, g, b)
    for pid, colors in palettes.items():
        for idx, rgb in colors.items():
            mat_name = f"mat_{pid}_{idx}"
            mat_entries[mat_name] = rgb

    # Fallback white material used when no palette reference is present.
    mat_entries['mat_default'] = (0.8, 0.8, 0.8)

    with open(mtl_path, 'w') as mf:
        mf.write(f"# Generated by build_walkable_scene.py\n")
        for mname, (r, g, b) in mat_entries.items():
            mf.write(f"\nnewmtl {mname}\n")
            mf.write(f"Ka {r:.6f} {g:.6f} {b:.6f}\n")   # ambient
            mf.write(f"Kd {r:.6f} {g:.6f} {b:.6f}\n")   # diffuse
            mf.write(f"Ks 0.1 0.1 0.1\n")                # specular
            mf.write(f"Ns 10.0\n")                        # shininess
            mf.write(f"d 1.0\n")                          # opacity

    log(f"MTL written: {mtl_path} ({len(mat_entries)} materials)")

    # --- Parse geometry and write OBJ ----------------------------------------
    with open(obj_path, 'w') as of:
        of.write(f"# Generated by build_walkable_scene.py\n")
        of.write(f"mtllib {mtl_filename}\n\n")

        global_vertex_offset = 0  # OBJ vertex indices are 1-based and global.

        for obj_el in root.findall('.//m:object', ns):
            obj_id   = obj_el.get('id', 'unknown')
            obj_name = obj_el.get('name', f'object_{obj_id}').replace(' ', '_')
            mesh_el  = obj_el.find('m:mesh', ns)
            if mesh_el is None:
                continue

            of.write(f"o {obj_name}\n")

            # --- Vertices ---
            verts_el = mesh_el.find('m:vertices', ns)
            vertices = []
            if verts_el is not None:
                for v in verts_el.findall('m:vertex', ns):
                    x, y, z = float(v.get('x', 0)), float(v.get('y', 0)), float(v.get('z', 0))
                    vertices.append((x, y, z))
                    of.write(f"v {x:.8f} {y:.8f} {z:.8f}\n")

            # --- Triangles --------------------------------------------------
            # Group consecutive triangles that share the same material together
            # so we minimise 'usemtl' line changes.
            tris_el = mesh_el.find('m:triangles', ns)
            if tris_el is None:
                global_vertex_offset += len(vertices)
                continue

            triangles = tris_el.findall('m:triangle', ns)

            # Determine per-triangle material name.
            current_mat  = None
            base_offset  = global_vertex_offset  # offset for this object's verts

            of.write(f"usemtl mat_default\n")  # prime with a default
            current_mat = 'mat_default'

            for tri in triangles:
                v1 = int(tri.get('v1')) + base_offset + 1  # OBJ is 1-indexed
                v2 = int(tri.get('v2')) + base_offset + 1
                v3 = int(tri.get('v3')) + base_offset + 1

                pid = tri.get('pid')
                p1  = tri.get('p1')
                if pid is not None and p1 is not None:
                    mat_name = f"mat_{pid}_{p1}"
                else:
                    mat_name = 'mat_default'

                if mat_name not in mat_entries:
                    mat_name = 'mat_default'

                if mat_name != current_mat:
                    of.write(f"usemtl {mat_name}\n")
                    current_mat = mat_name

                of.write(f"f {v1} {v2} {v3}\n")

            global_vertex_offset += len(vertices)
            of.write("\n")

    log(f"OBJ written: {obj_path} ({global_vertex_offset} vertices total)")


